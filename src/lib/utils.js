import JSZip from 'jszip'

/**
 * Build a file tree object from flat file array
 */
export const buildFileTree = (files) => {
  const tree = {}
  files.forEach((file) => {
    const parts = file.path.split('/')
    let node = tree
    parts.forEach((part, i) => {
      if (i === parts.length - 1) {
        node[part] = { ...file, isFile: true }
      } else {
        if (!node[part]) node[part] = { isFile: false, children: {} }
        node = node[part].children
      }
    })
  })
  return tree
}

